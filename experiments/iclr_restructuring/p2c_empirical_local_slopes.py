"""Empirical secant-slope diagnostic for the collision mechanism.

The symbolic proposition in ``main_v2.tex`` is stated for a fixed Lipschitz
class.  This audit reports model-specific pairwise output separation divided
by the frozen feature distance for the Src L410A/F405A near-collision.  These
are empirical secant slopes, not fitted global Lipschitz constants.  Exact
Abl1 F382 collisions are recorded separately because their feature-distance
denominator is zero.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
COLLISION = RESULTS / "p2c_feature_collision.json"
REVIEW = RESULTS / "t5_review_responses.json"
# (unused SCALE constant, a duplicate of REVIEW, removed 2026-08-17)
OUT_JSON = RESULTS / "p2c_empirical_local_slopes.json"
OUT_MD = RESULTS / "p2c_empirical_local_slopes_report.md"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    collision = json.loads(COLLISION.read_text(encoding="utf-8"))
    review = json.loads(REVIEW.read_text(encoding="utf-8"))
    pair = review["collision_separation"]
    d_feat = float(pair["d_feat"])
    delta_l1 = float(pair["delta_l1"])
    models = {}
    for name, values in pair["models"].items():
        sep = float(values["output_separation_l1"])
        models[name] = {
            "output_separation_l1": sep,
            "secant_slope_output_l1_per_feature_l2": sep / d_feat,
        }
    scale = review["scale_sensitivity"]
    scale_rows = {
        str(scale_factor): {
            "d_feat": float(values["d_feat"]),
            "in_collision_range": bool(values["in_collision_range"]),
        }
        for scale_factor, values in scale.items()
    }
    result = {
        "schema": "p2c_empirical_local_slopes_v1",
        "definition": "full-data fitted output separation / frozen 1x feature distance; diagnostic secant slope, not global Lipschitz estimate",
        "pair": pair["pair"],
        "feature_distance_l2": d_feat,
        "target_shift_distance_l1": delta_l1,
        "models": models,
        "exact_collision_control": {
            "system": "abl1",
            "group": "F382L/F382Y/F382V",
            "feature_distance_l2": float(collision["abl1_pos"]["F382L"]["d_feat_l2_min"]),
            "slope": None,
            "note": "zero denominator; treated as an exact collision rather than assigned a numerical slope",
        },
        "position_scale_sensitivity": scale_rows,
        "source_hashes": {
            "collision": sha256_file(COLLISION),
            "review": sha256_file(REVIEW),
        },
    }
    OUT_JSON.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = [
        "# Empirical collision secant slopes",
        "",
        "For Src L410A/F405A, the frozen position-marker feature distance is "
        f"{d_feat:.6f} and the target shift distance is {delta_l1:.2f}. "
        "The values below are fitted-output secant slopes, not global "
        "Lipschitz estimates.",
        "",
        "| Model | Output separation (L1) | Secant slope |",
        "|---|---:|---:|",
    ]
    for name, values in models.items():
        lines.append(
            f"| {name} | {values['output_separation_l1']:.4f} | "
            f"{values['secant_slope_output_l1_per_feature_l2']:.2f} |"
        )
    lines.extend([
        "",
        "The Abl1 F382 group is an exact collision (zero feature distance), so no finite secant slope is reported. Position scaling retains the Src conflict region from 0.01x through 10x and exits it at 100x; this is a coordinate-sensitivity check, not a refit-based smoothness estimate.",
        "",
        "Source: `p2c_feature_collision.json` and `t5_review_responses.json`; generated by `p2c_empirical_local_slopes.py`.",
    ])
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({name: round(values["secant_slope_output_l1_per_feature_l2"], 4)
                      for name, values in models.items()}, indent=2))


if __name__ == "__main__":
    main()
